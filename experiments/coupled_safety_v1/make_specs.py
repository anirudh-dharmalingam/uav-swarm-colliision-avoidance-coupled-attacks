#!/usr/bin/env python3
"""Spec builders for the coupled-safety campaign (specs run with scripts/coupled_safety/cs_batch.py).

    python3 experiments/coupled_safety_v1/make_specs.py calib            # Gate C: 12 train (11000-11011) + 12 holdout (11100-11111) HF1 flights
    python3 experiments/coupled_safety_v1/make_specs.py dev [--setting S0|S1|S2] [--seeds 12000-12007] ...
Confirmatory specs (E1-E5) are generated by make_confirmatory.py from the FROZEN selection.  Scenario draws are produced in advance
by scenarios.py (SCENARIOS.jsonl); nothing here consumes random numbers at run time.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).parent
SPECS = HERE / "specs"
ROOT = HERE.parents[1]


def merge(*ds):
    out = {}
    for d in ds:
        for k, v in d.items():
            if isinstance(v, dict) and isinstance(out.get(k), dict):
                out[k] = merge(out[k], v)
            else:
                out[k] = v
    return out


def calib():
    eps = []
    for split, seeds in (("train", range(11000, 11012)), ("holdout", range(11100, 11112))):
        for sd in seeds:
            eps.append({"name": f"calib_{split}_s{sd}", "meta": {"split": split, "mode": "acceleration", "jerk": 8.0},
                        "overrides": {"experiment": {"seed": sd}, "controller": {"mode": "hf1", "script": "hf1_tracking_node.py"},
                                      "hf1": {"mode": "acceleration", "jerk": 8.0, "hold_s": 1.5, "vmax": 4.0, "cell_m": 4.0, "velocity_tau_s": 0.5}}})
    spec = {"tag": "calib", "base": "config/swarm/ral26_base.toml", "results_root": "results/coupled_safety_v1",
            "common": {"experiment": {"duration_s": 90.0}, "swarm": {"num_uavs": 6}, "formation": {"spacing_m": 30.0}, "ral26": {"truth_hz": 50.0}},
            "episodes": eps}
    (SPECS / "calib.json").write_text(json.dumps(spec, indent=1))
    print("calib", len(eps))


def _common():
    import sys
    sys.path.insert(0, str(HERE))
    import runs
    scn = runs.load_scenarios()
    b = json.loads((HERE / "bounds_declared.json").read_text())["bounds"]
    return runs, scn, b


def _write(tag, eps, rtf=0.95):
    spec = {"tag": tag, "base": "config/swarm/coupled_safety_base.toml", "results_root": "results/coupled_safety_v1",
            "rtf_rerun_below": rtf, "episodes": eps}
    (SPECS / f"{tag}.json").write_text(json.dumps(spec, indent=1))
    print(tag, len(eps))


def dev_benign(settings=("S0", "S1", "S2")):
    runs, scn, b = _common()
    eps = [runs.episode(scn[f"dev-N6-{sd}"], "A0", "D24R", "nominal", st, b) for st in settings for sd in range(12000, 12008)]
    _write("dev_benign", eps)


def dev_attack(setting):
    runs, scn, b = _common()
    eps = []
    for sd in range(12000, 12008):
        for cell in ("A0", "PHYS", "REPORT", "COUPLED"):
            eps.append(runs.episode(scn[f"dev-N6-{sd}"], cell, "D24R", "nominal", setting, b))
        eps.append(runs.episode(scn[f"dev-N6-{sd}"], "COUPLED", "D0R", "nominal", setting, b))
    _write(f"dev_attack_{setting}", eps)


def dev_e3(setting, shifts):
    """E3 offset bracketing on DEVELOPMENT seeds: COUPLED, D24R and D0R, attacker slot shifted TOWARD its nearest honest neighbour (the encounter victim) by `shift` m along the encounter direction (initial clearance to the victim = spacing - shift)."""
    runs, scn, b = _common()
    import sys
    sys.path.insert(0, str(ROOT / "scripts" / "swarm"))
    from experiment_manager import generate_lattice
    S = runs.SETTINGS[setting]
    off = generate_lattice(6, S["spacing_m"], 1.0)[0]
    eps = []
    for sd in range(12000, 12004):
        sc = scn[f"dev-N6-{sd}"]
        a = sc["attacker_id"]
        dists = sorted((((off[a][0] - off[j][0]) ** 2 + (off[a][1] - off[j][1]) ** 2) ** 0.5, j) for j in range(6) if j != a)
        j = dists[0][1]
        ux, uy = (off[j][0] - off[a][0]) / dists[0][0], (off[j][1] - off[a][1]) / dists[0][0]   # unit vector attacker -> nearest neighbour
        for sh in shifts:
            for m in ("D24R", "D0R"):
                eps.append(runs.episode(sc, "COUPLED", m, "nominal", setting, b, slot_shift={"id": a, "dx": round(sh * ux, 4), "dy": round(sh * uy, 4), "toward": j, "shift_toward_m": sh},
                                        name=f"dev-E3T-{setting}-{m}-t{int(round(sh * 10)):02d}-s{sd}"))
    _write(f"dev_e3t_{setting}", eps)


def dev_smoke():
    """Development smoke of every confirmatory code path on dev scenarios (nothing here is a confirmatory seed)."""
    runs, scn, b = _common()
    s0 = scn["dev-N6-12000"]
    eps = []
    for info in ("identity", "oracle", "sensor"):
        eps.append(runs.episode(s0, "COUPLED", "D24R", "nominal", "S0", b, info=info))
    eps.append(runs.episode(s0, "COUPLED", "D24R", "adverse", "S0", b))
    for m in ("D26", "D24R_NOSQ"):
        eps.append(runs.episode(s0, "COUPLED", m, "nominal", "S0", b))
    for n in (4, 8):
        eps.append(runs.episode(scn[f"dev-N{n}-12000"], "COUPLED", "D24R", "nominal", "S0", b))
    eps.append(runs.episode(s0, "COUPLED", "D24R", "nominal", "S0", b, violation="report", name="dev-E5-report-S0-s12000",
                            attack_override={"beta_attack": 3.0, "beta_v_attack": 1.5}))
    eps.append(runs.episode(s0, "COUPLED", "D24R", "nominal", "S0", b, violation="accel", name="dev-E5-accel-S0-s12000",
                            attack_override={"epsilon": 6.0}))
    _write("dev_smoke", eps)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("which", choices=["calib", "dev_benign", "dev_attack", "dev_e3", "dev_smoke"])
    ap.add_argument("--setting", default="S0")
    ap.add_argument("--shifts", default="0,1,2,3")
    a = ap.parse_args()
    if a.which == "calib":
        calib()
    elif a.which == "dev_benign":
        dev_benign()
    elif a.which == "dev_smoke":
        dev_smoke()
    elif a.which == "dev_attack":
        dev_attack(a.setting)
    else:
        dev_e3(a.setting, [float(x) for x in a.shifts.split(",")])
